#!/usr/bin/env python3
"""
Writes WearMesh's icon: the Android vector drawables, an SVG of the mark, and PNGs, from one
description.

The icon is the Colorado Mesh mark (mountains under an arc with a node at its top, in the
Colorado Mesh palette, from Colorado-Mesh/branding), with the arc closed into a watch's bezel and
a crown on its right-hand side, where the Pixel Watch has its crown. It is drawn the same way as
MeshCore TAK Bridge's icon, which closes the arc into a map crosshair instead, so the two read as
one family. Run it from the repository root after changing the shapes or colours below:

    python3 docs/icon/make_icon.py

Outputs:
    wear/src/main/res/drawable/ic_launcher_background.xml
    wear/src/main/res/drawable/ic_launcher_foreground.xml
    wear/src/main/res/drawable/ic_launcher_monochrome.xml   (themed icons)
    wear/src/main/res/drawable/ic_notification.xml          (status bar and notifications)
    wear/src/main/res/mipmap-anydpi-v26/ic_launcher.xml and ic_launcher_round.xml
    docs/icon/icon.svg            (the full-colour mark, 108 x 108)
    docs/icon/icon-512.png        (round, for the README, the repository and a store listing)
    docs/icon/preview.png         (launcher size, themed and notification versions side by side)

The PNGs need cairosvg (pip install cairosvg); without it the script skips them and says so.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
RES = ROOT / "wear/src/main/res"
DOCS = ROOT / "docs/icon"

# Colorado Mesh palette (Colorado-Mesh/branding, colors/colors.css), as in the bridge's icon.
NAVY_TOP, NAVY_BOTTOM = "#011033", "#0A4483"  # blue-9, blue-5
RED, YELLOW, LIGHT_YELLOW = "#DD506D", "#F2B138", "#ECC455"  # red-3, yellow-5, yellow-3
BACK_PEAK = "#16538E"  # blue-1
SNOW_TOP, SNOW_BOTTOM = "#FFFFFF", "#7C9CC8"
GREEN_TOP, GREEN_BOTTOM = "#4CB578", "#106641"  # green-3, green-6
OFF_WHITE = "#EDEDED"

# Geometry, in the 108 x 108 adaptive icon grid. A watch launcher shows the icon as a circle; keep
# everything within a radius of 33 around the centre (54, 54).
# The bezel is as large as the safe zone allows once the crown is added; the node sits on it at
# 12 o'clock, where a watch has its 12 mark.
RING_CX, RING_CY, RING_R, RING_W = 53, 55, 27, 3
NODE_CX, NODE_CY = 53, 28
# The crown: a short rounded bar standing out from the bezel at 3 o'clock.
CROWN_X, CROWN_Y, CROWN_W, CROWN_H = RING_CX + RING_R + 0.6, RING_CY - 5, 4.6, 10
# The landscape fills the dial down to the bezel, like a watch face; the clip rounds it off.
BACK = [(24, 86), (42, 57), (60, 86)]
MAIN = [(34, 86), (57, 45), (82, 86)]
SNOWCAP = [(57, 45), (51, 52.8), (54.6, 51.6), (57, 54.6), (60.6, 51), (63.6, 52.8)]
# The status bar icon's 64-unit viewport starts here.
NOTIFICATION_X, NOTIFICATION_Y = 23, 21.5
NOTIFICATION_VIEW = f"{NOTIFICATION_X} {NOTIFICATION_Y} 64 64"
HILLS = [(24, 72.5), (39, 64), (47.5, 68.5), (61, 59.5), (84, 71.5), (84, 86), (24, 86)]


def n(v):
    return f"{round(v, 3):g}"


def poly(points):
    return "M" + " L".join(f"{n(x)},{n(y)}" for x, y in points) + " Z"


def circle(cx, cy, r):
    return (f"M{n(cx - r)},{n(cy)} A{n(r)},{n(r)} 0 1,1 {n(cx + r)},{n(cy)} "
            f"A{n(r)},{n(r)} 0 1,1 {n(cx - r)},{n(cy)} Z")


def rounded_rect(x, y, w, h, r):
    return (f"M{n(x + r)},{n(y)} H{n(x + w - r)} A{n(r)},{n(r)} 0 0,1 {n(x + w)},{n(y + r)} "
            f"V{n(y + h - r)} A{n(r)},{n(r)} 0 0,1 {n(x + w - r)},{n(y + h)} H{n(x + r)} "
            f"A{n(r)},{n(r)} 0 0,1 {n(x)},{n(y + h - r)} V{n(y + r)} A{n(r)},{n(r)} 0 0,1 {n(x + r)},{n(y)} Z")


def line(x1, y1, x2, y2):
    return f"M{n(x1)},{n(y1)} L{n(x2)},{n(y2)}"


def crown():
    return rounded_rect(CROWN_X, CROWN_Y, CROWN_W, CROWN_H, 1.6)


def argb(hex_rgb, alpha):
    return f"#{alpha:02X}{hex_rgb[1:]}"


# --- Android vector drawables -------------------------------------------------------------

HEADER = ('<?xml version="1.0" encoding="utf-8"?>\n'
          "<!-- Generated by docs/icon/make_icon.py; edit that and run it again. -->\n")


def vector(body, size=108, viewport=108, aapt=False):
    ns = ' xmlns:aapt="http://schemas.android.com/aapt"' if aapt else ""
    return (HEADER + f'<vector xmlns:android="http://schemas.android.com/apk/res/android"{ns}\n'
            f'    android:width="{size}dp"\n    android:height="{size}dp"\n'
            f'    android:viewportWidth="{viewport}"\n    android:viewportHeight="{viewport}">\n'
            + body + "</vector>\n")


def vd_linear(attr, x1, y1, x2, y2, stops):
    items = "".join(f'                <item android:offset="{n(o)}" android:color="{c}" />\n' for o, c in stops)
    return (f'        <aapt:attr name="{attr}">\n'
            f'            <gradient android:type="linear" android:startX="{n(x1)}" android:startY="{n(y1)}"'
            f' android:endX="{n(x2)}" android:endY="{n(y2)}">\n{items}'
            "            </gradient>\n        </aapt:attr>\n")


def vd_path(data, fill=None, stroke=None, width=None, gradient=None, cap=None, indent="    "):
    attrs = [f'android:pathData="{data}"']
    if fill:
        attrs.append(f'android:fillColor="{fill}"')
    if stroke:
        attrs.append(f'android:strokeColor="{stroke}"')
    if width:
        attrs.append(f'android:strokeWidth="{n(width)}"')
    if cap:
        attrs.append(f'android:strokeLineCap="{cap}"')
    sep = "\n" + indent + "    "
    if gradient:
        return f"{indent}<path{sep}{sep.join(attrs)}>\n{gradient}{indent}</path>\n"
    return f"{indent}<path{sep}{sep.join(attrs)} />\n"


def background_vd():
    grad = vd_linear("android:fillColor", 54, 0, 54, 108, [(0, NAVY_TOP), (1, NAVY_BOTTOM)])
    return vector(vd_path("M0,0 H108 V108 H0 Z", gradient=grad), aapt=True)


def ring_gradient(attr):
    return vd_linear(attr, RING_CX - RING_R, 0, RING_CX + RING_R, 0, [(0, RED), (0.5, YELLOW), (1, LIGHT_YELLOW)])


def foreground_vd():
    clip = f'        <clip-path android:pathData="{circle(RING_CX, RING_CY, RING_R - 1.4)}" />\n'
    snow = vd_linear("android:fillColor", 0, 45, 0, 74, [(0, SNOW_TOP), (1, SNOW_BOTTOM)])
    hills = vd_linear("android:fillColor", 0, 59.5, 0, 86, [(0, GREEN_TOP), (1, GREEN_BOTTOM)])
    glow = (f'        <aapt:attr name="android:fillColor">\n'
            f'            <gradient android:type="radial" android:centerX="{NODE_CX}" android:centerY="{NODE_CY}"'
            f' android:gradientRadius="7">\n'
            f'                <item android:offset="0" android:color="{argb(YELLOW, 0xCC)}" />\n'
            f'                <item android:offset="1" android:color="{argb(YELLOW, 0x00)}" />\n'
            "            </gradient>\n        </aapt:attr>\n")
    body = vd_path(crown(), fill=LIGHT_YELLOW)
    body += "    <group>\n" + clip
    body += vd_path(poly(BACK), fill=BACK_PEAK, indent="        ")
    body += vd_path(poly(MAIN), gradient=snow, indent="        ")
    body += vd_path(poly(SNOWCAP), fill=SNOW_TOP, indent="        ")
    body += vd_path(poly(HILLS), gradient=hills, indent="        ")
    body += "    </group>\n"
    body += vd_path(circle(RING_CX, RING_CY, RING_R), width=RING_W, gradient=ring_gradient("android:strokeColor"))
    body += vd_path(circle(NODE_CX, NODE_CY, 7), gradient=glow)
    body += vd_path(circle(NODE_CX, NODE_CY, 3.2), fill=YELLOW, stroke=SNOW_TOP, width=1)
    return vector(body, aapt=True)


def mark_paths(colour, ring_width, node_r=4.4):
    """The mark in one colour: for themed launcher icons and the status bar."""
    body = vd_path(crown(), fill=colour)
    body += "    <group>\n"
    body += f'        <clip-path android:pathData="{circle(RING_CX, RING_CY, RING_R - 1.4)}" />\n'
    for shape in (BACK, MAIN, HILLS):
        body += vd_path(poly(shape), fill=colour, indent="        ")
    body += "    </group>\n"
    body += vd_path(circle(RING_CX, RING_CY, RING_R), stroke=colour, width=ring_width)
    body += vd_path(circle(NODE_CX, NODE_CY, node_r), fill=colour)
    return body


def monochrome_vd():
    return vector(mark_paths("#FFFFFFFF", RING_W))


def notification_vd():
    # Status bar icons are 24 dp and drawn in white by the system. The mark spans about 24.5 to
    # 85.2 across and 23.2 to 83.5 down; a viewport of 64 from (23, 21.5) gives it a little margin,
    # and a heavier ring and node keep it legible at that size.
    body = f'    <group android:translateX="{n(-NOTIFICATION_X)}" android:translateY="{n(-NOTIFICATION_Y)}">\n'
    body += vd_path(crown(), fill="#FFFFFFFF", indent="        ")
    body += "        <group>\n"
    body += f'            <clip-path android:pathData="{circle(RING_CX, RING_CY, RING_R - 1.4)}" />\n'
    for shape in (BACK, MAIN, HILLS):
        body += vd_path(poly(shape), fill="#FFFFFFFF", indent="            ")
    body += "        </group>\n"
    body += vd_path(circle(RING_CX, RING_CY, RING_R), stroke="#FFFFFFFF", width=3.8, indent="        ")
    body += vd_path(circle(NODE_CX, NODE_CY, 4.8), fill="#FFFFFFFF", indent="        ")
    body += "    </group>\n"
    return vector(body, size=24, viewport=64)


ADAPTIVE = ('<?xml version="1.0" encoding="utf-8"?>\n'
            "<!-- Generated by docs/icon/make_icon.py; edit that and run it again. -->\n"
            '<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <background android:drawable="@drawable/ic_launcher_background" />\n'
            '    <foreground android:drawable="@drawable/ic_launcher_foreground" />\n'
            '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n'
            "</adaptive-icon>\n")


# --- SVG ----------------------------------------------------------------------------------

def mark_svg(round_mask=False, size=108):
    """The full-colour icon as SVG; with round_mask, cut to the circle a watch launcher shows."""
    def pts(points):
        return " ".join(f"{n(x)},{n(y)}" for x, y in points)
    # A launcher shows the middle 72 of the 108 grid; the round version shows that circle only.
    view = "18 18 72 72" if round_mask else "0 0 108 108"
    mask_open = '<g clip-path="url(#launcher)">' if round_mask else "<g>"
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" width="{size}" height="{size}">
<!-- Generated by docs/icon/make_icon.py; edit that and run it again. -->
<defs>
<linearGradient id="bg" gradientUnits="userSpaceOnUse" x1="54" y1="0" x2="54" y2="108"><stop offset="0" stop-color="{NAVY_TOP}"/><stop offset="1" stop-color="{NAVY_BOTTOM}"/></linearGradient>
<linearGradient id="ring" gradientUnits="userSpaceOnUse" x1="{n(RING_CX - RING_R)}" y1="0" x2="{n(RING_CX + RING_R)}" y2="0"><stop offset="0" stop-color="{RED}"/><stop offset="0.5" stop-color="{YELLOW}"/><stop offset="1" stop-color="{LIGHT_YELLOW}"/></linearGradient>
<linearGradient id="snow" gradientUnits="userSpaceOnUse" x1="0" y1="45" x2="0" y2="74"><stop offset="0" stop-color="{SNOW_TOP}"/><stop offset="1" stop-color="{SNOW_BOTTOM}"/></linearGradient>
<linearGradient id="hills" gradientUnits="userSpaceOnUse" x1="0" y1="59.5" x2="0" y2="86"><stop offset="0" stop-color="{GREEN_TOP}"/><stop offset="1" stop-color="{GREEN_BOTTOM}"/></linearGradient>
<radialGradient id="glow" gradientUnits="userSpaceOnUse" cx="{NODE_CX}" cy="{NODE_CY}" r="7"><stop offset="0" stop-color="{YELLOW}" stop-opacity="0.8"/><stop offset="1" stop-color="{YELLOW}" stop-opacity="0"/></radialGradient>
<clipPath id="inside"><circle cx="{RING_CX}" cy="{RING_CY}" r="{n(RING_R - 1.4)}"/></clipPath>
<clipPath id="launcher"><circle cx="54" cy="54" r="36"/></clipPath>
</defs>
{mask_open}
<rect width="108" height="108" fill="url(#bg)"/>
<path d="{crown()}" fill="{LIGHT_YELLOW}"/>
<g clip-path="url(#inside)">
<polygon points="{pts(BACK)}" fill="{BACK_PEAK}"/>
<polygon points="{pts(MAIN)}" fill="url(#snow)"/>
<polygon points="{pts(SNOWCAP)}" fill="{SNOW_TOP}"/>
<polygon points="{pts(HILLS)}" fill="url(#hills)"/>
</g>
<circle cx="{RING_CX}" cy="{RING_CY}" r="{RING_R}" fill="none" stroke="url(#ring)" stroke-width="{RING_W}"/>
<circle cx="{NODE_CX}" cy="{NODE_CY}" r="7" fill="url(#glow)"/>
<circle cx="{NODE_CX}" cy="{NODE_CY}" r="3.2" fill="{YELLOW}" stroke="{SNOW_TOP}" stroke-width="1"/>
</g>
</svg>
"""


def one_colour_svg(colour, background, ring_width, node_r, view="18 18 72 72", size=108):
    def pts(points):
        return " ".join(f"{n(x)},{n(y)}" for x, y in points)
    bg = f'<circle cx="54" cy="54" r="36" fill="{background}"/>' if background else ""
    return f"""<svg xmlns="http://www.w3.org/2000/svg" viewBox="{view}" width="{size}" height="{size}">
<defs><clipPath id="inside"><circle cx="{RING_CX}" cy="{RING_CY}" r="{n(RING_R - 1.4)}"/></clipPath></defs>
{bg}<path d="{crown()}" fill="{colour}"/>
<g clip-path="url(#inside)">{"".join(f'<polygon points="{pts(s)}" fill="{colour}"/>' for s in (BACK, MAIN, HILLS))}</g>
<circle cx="{RING_CX}" cy="{RING_CY}" r="{RING_R}" fill="none" stroke="{colour}" stroke-width="{n(ring_width)}"/>
<circle cx="{NODE_CX}" cy="{NODE_CY}" r="{n(node_r)}" fill="{colour}"/>
</svg>
"""


def write_pngs():
    try:
        import cairosvg
    except ImportError:
        print("cairosvg is not installed, so the PNGs were not written (pip install cairosvg)")
        return
    from io import BytesIO
    cairosvg.svg2png(bytestring=mark_svg(round_mask=True).encode(), write_to=str(DOCS / "icon-512.png"),
                     output_width=512, output_height=512)
    try:
        from PIL import Image
    except ImportError:
        print("Pillow is not installed, so preview.png was not written (pip install pillow)")
        return
    # Launcher size on a watch (about 48 dp, drawn here at 3x), the themed icon, and the
    # notification icon at its real 24 dp size and at 3x.
    tiles = [
        cairosvg.svg2png(bytestring=mark_svg(round_mask=True).encode(), output_width=144, output_height=144),
        cairosvg.svg2png(bytestring=one_colour_svg("#D7E3FF", "#2B3A55", RING_W, 4.4).encode(),
                         output_width=144, output_height=144),
        cairosvg.svg2png(bytestring=one_colour_svg("#FFFFFF", None, 3.8, 4.8,
                                                   view=NOTIFICATION_VIEW).encode(), output_width=72, output_height=72),
        cairosvg.svg2png(bytestring=one_colour_svg("#FFFFFF", None, 3.8, 4.8,
                                                   view=NOTIFICATION_VIEW).encode(), output_width=24, output_height=24),
    ]
    images = [Image.open(BytesIO(t)).convert("RGBA") for t in tiles]
    width = sum(i.width for i in images) + 24 * (len(images) + 1)
    sheet = Image.new("RGBA", (width, 192), (24, 24, 24, 255))
    x = 24
    for image in images:
        sheet.alpha_composite(image, (x, (192 - image.height) // 2))
        x += image.width + 24
    sheet.save(DOCS / "preview.png")


if __name__ == "__main__":
    drawable = RES / "drawable"
    mipmap = RES / "mipmap-anydpi-v26"
    for folder in (drawable, mipmap, DOCS):
        folder.mkdir(parents=True, exist_ok=True)
    (drawable / "ic_launcher_background.xml").write_text(background_vd())
    (drawable / "ic_launcher_foreground.xml").write_text(foreground_vd())
    (drawable / "ic_launcher_monochrome.xml").write_text(monochrome_vd())
    (drawable / "ic_notification.xml").write_text(notification_vd())
    (mipmap / "ic_launcher.xml").write_text(ADAPTIVE)
    (mipmap / "ic_launcher_round.xml").write_text(ADAPTIVE)
    (DOCS / "icon.svg").write_text(mark_svg())
    write_pngs()
    print("Wrote the icon drawables, the launcher icons, docs/icon/icon.svg and the PNGs")
